CREATE TABLE IF NOT EXISTS yz_user (
  id BIGINT PRIMARY KEY AUTO_INCREMENT, username VARCHAR(64) NOT NULL UNIQUE, password VARCHAR(100) NOT NULL,
  real_name VARCHAR(64) NOT NULL, role VARCHAR(24) NOT NULL, phone VARCHAR(20) DEFAULT '', enabled TINYINT NOT NULL DEFAULT 1,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS citizen_report (
  id BIGINT PRIMARY KEY AUTO_INCREMENT, report_no VARCHAR(32) NOT NULL UNIQUE, phone VARCHAR(20) NOT NULL,
  kind VARCHAR(16) NOT NULL, media_name VARCHAR(255) DEFAULT '', location VARCHAR(255) NOT NULL, description VARCHAR(1000) DEFAULT '',
  status VARCHAR(24) NOT NULL DEFAULT 'submitted', risk_flag TINYINT NOT NULL DEFAULT 0, event_id VARCHAR(40) DEFAULT '', task_id VARCHAR(40) DEFAULT '',
  public_reply VARCHAR(1000) DEFAULT '', reject_reason VARCHAR(1000) DEFAULT '', submitted_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  accepted_at DATETIME NULL, started_at DATETIME NULL, finished_at DATETIME NULL, rejected_at DATETIME NULL
);
CREATE TABLE IF NOT EXISTS work_order (
  id BIGINT PRIMARY KEY AUTO_INCREMENT, order_no VARCHAR(32) NOT NULL UNIQUE, report_no VARCHAR(32) DEFAULT '', event_id VARCHAR(40) DEFAULT '',
  camera_id VARCHAR(40) DEFAULT 'CAM-037', location_name VARCHAR(255) NOT NULL, latitude DECIMAL(10,6) DEFAULT 32.126200,
  longitude DECIMAL(10,6) DEFAULT 114.067400, status VARCHAR(24) NOT NULL DEFAULT 'pending', assigned_to VARCHAR(64) DEFAULT '待派发',
  priority VARCHAR(20) DEFAULT '常规', closure_photo VARCHAR(500) DEFAULT '', completion_note VARCHAR(1000) DEFAULT '',
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, accepted_at DATETIME NULL, completed_at DATETIME NULL, response_time_sec INT NULL, escalated TINYINT DEFAULT 0
);
CREATE TABLE IF NOT EXISTS activity_log (
  id BIGINT PRIMARY KEY AUTO_INCREMENT, source VARCHAR(20) NOT NULL, action VARCHAR(50) NOT NULL, actor VARCHAR(64) NOT NULL,
  target VARCHAR(80) NOT NULL, detail VARCHAR(500) NOT NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  INDEX idx_activity_created(created_at)
);
